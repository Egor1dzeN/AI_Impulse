TOOL_CALL_FORMAT = (
    "Если нужно вызвать функцию — ответь ТОЛЬКО одним блоком вида:\n"
    "```tool_call\n"
    '{{"name": "имя_функции", "arguments": {{"ключ": "значение"}}}}\n'
    "```\n"
    "без какого-либо другого текста вокруг. Если действие не требуется и у "
    "тебя уже достаточно информации — просто ответь пользователю обычным "
    "текстом, без блока tool_call. Никогда не выдумывай функции, которых нет "
    "в списке доступных функций. Сегодняшняя дата: {today}."
)


def build_system_prompt(
    today: str, intervals_icu_connected: bool = False, google_calendar_connected: bool = False
) -> str:
    return "\n\n".join(
        [
            PERSONA,
            HISTORY_INSTRUCTIONS,
            MEMORY_INSTRUCTIONS,
            ACTION_INSTRUCTIONS,
            INFO_TOOL_INSTRUCTIONS,
            WORKOUT_INSTRUCTIONS if intervals_icu_connected else WORKOUT_NOT_CONNECTED_INSTRUCTIONS,
            CALENDAR_INSTRUCTIONS if google_calendar_connected else CALENDAR_NOT_CONNECTED_INSTRUCTIONS,
            TOOL_CALL_FORMAT.format(today=today),
        ]
    )
