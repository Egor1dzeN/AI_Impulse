            MEMORY_INSTRUCTIONS,
            DATA_INSTRUCTIONS,
            SECURITY_INSTRUCTIONS,
            EXPLAINABILITY_INSTRUCTIONS,
            ANSWER_STYLE_INSTRUCTIONS,
            PROACTIVE_INSTRUCTIONS,
            ACTION_INSTRUCTIONS,
            INFO_TOOL_INSTRUCTIONS,
            PRODUCT_INFO_INSTRUCTIONS,
